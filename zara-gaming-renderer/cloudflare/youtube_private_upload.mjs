// Owner-controlled YouTube PRIVATE upload pilot. Never automatically publishes.
// Only an authorized, manually dispatched GitHub Actions workflow may call it.
import {hasValidGitHubIdentity} from './render_runner.mjs';
import {googleUploadAccessToken, youtubeConnected} from './youtube_oauth.mjs';

const MAX_BYTES = 35 * 1024 * 1024;
const PRIVATE_ONLY = true;

function json(value, status=200) {
  return Response.json(value,{status,headers:{'Cache-Control':'no-store',
    'X-Content-Type-Options':'nosniff','Referrer-Policy':'no-referrer'}});
}

function hex(buffer) {
  return [...new Uint8Array(buffer)].map(x=>x.toString(16).padStart(2,'0')).join('');
}

export async function routePrivateUpload(request, env) {
  const url=new URL(request.url);
  if (!url.pathname.startsWith('/upload/')) return null;
  if (url.pathname==='/upload/status' && request.method==='GET') {
    return json({private_upload_api_installed:true,private_upload_enabled:PRIVATE_ONLY,
      youtube_oauth_connected:await youtubeConnected(env),public_publishing_enabled:false,
      automatic_publishing_enabled:false,max_mp4_bytes:MAX_BYTES});
  }
  if (url.pathname!=='/upload/private' || request.method!=='POST') return json({error:'not_found'},404);
  if (!(await hasValidGitHubIdentity(request,['workflow_dispatch']))) return json({error:'manual_github_identity_required'},401);
  if (!PRIVATE_ONLY) return json({error:'private_upload_disabled'},503);
  const len=Number(request.headers.get('Content-Length')||0);
  if (!Number.isSafeInteger(len) || len<1024 || len>MAX_BYTES || !request.body) return json({error:'invalid_mp4_size'},413);
  if (request.headers.get('Content-Type')?.split(';')[0].toLowerCase()!=='video/mp4') return json({error:'mp4_required'},415);
  const mode=request.headers.get('X-Zara-Video-Kind')||'';
  if (!['synthetic-upload-test','approved-editorial'].includes(mode)) return json({error:'content_mode_required'},422);
  const jobId=(url.searchParams.get('job_id')||'').trim();
  if (mode==='approved-editorial' && !/^\d{4}-\d{2}-\d{2}:(short|long)$/.test(jobId)) return json({error:'job_id_required'},422);

  // Small media is deliberately bounded here; unlike an unbounded formData()
  // call this cannot consume the Worker's entire 128 MiB heap.
  const media=await request.arrayBuffer();
  if (media.byteLength!==len) return json({error:'incomplete_media'},400);
  const sha=hex(await crypto.subtle.digest('SHA-256',media));
  const old=await env.DB.prepare('SELECT youtube_id FROM youtube_private_uploads WHERE media_sha256=? AND youtube_id IS NOT NULL').bind(sha).first();
  if (old) return json({status:'already_uploaded_private',youtube_id:old.youtube_id,privacy:'private'});

  let title='Zara Gaming Cloud - PRIVATE Upload Functionality Test';
  let description='Synthetic diagnostic footage generated by Zara Gaming Cloud. No real gameplay. Private upload functionality test only.';
  let category='22';
  if (mode==='approved-editorial') {
    const approval=await env.DB.prepare('SELECT job_id, rights_note FROM approved_video_media WHERE media_sha256=? AND job_id=?').bind(sha,jobId).first();
    if (!approval || !approval.rights_note || approval.rights_note.length<12) return json({error:'rights_approval_missing'},403);
    const job=await env.DB.prepare('SELECT game,topic FROM production_jobs WHERE id=?').bind(jobId).first();
    if (!job) return json({error:'unknown_editorial_job'},404);
    title=`${job.game} | ${job.topic}`.slice(0,95);
    description=`Zara Gaming original ranked video. Rights record: ${approval.rights_note.slice(0,380)}. First review copy. No voiceover.`;
    category='20';
  } else {
    // One synthetic test upload is enough. No repeat test spam.
    const check=await env.DB.prepare("SELECT COUNT(*) AS n FROM youtube_private_uploads WHERE content_mode='synthetic-upload-test' AND youtube_id IS NOT NULL").first();
    if ((check?.n||0)>0) return json({error:'synthetic_test_already_completed'},409);
  }

  let token;
  try { token=await googleUploadAccessToken(env); }
  catch(error) { console.error(JSON.stringify({event:'yt_refresh_error',kind:error?.message||'unknown'})); return json({error:'youtube_token_unavailable'},503); }
  const init=await fetch('https://www.googleapis.com/upload/youtube/v3/videos?uploadType=resumable&part=snippet,status',{
    method:'POST',headers:{'Authorization':`Bearer ${token}`,'Content-Type':'application/json; charset=UTF-8',
      'X-Upload-Content-Length':String(media.byteLength),'X-Upload-Content-Type':'video/mp4'},
    body:JSON.stringify({snippet:{title,description,categoryId:category},
      status:{privacyStatus:'private',selfDeclaredMadeForKids:false}}),
  });
  const location=init.headers.get('Location')||'';
  if (!init.ok || !/^https:\/\/www\.googleapis\.com\/upload\/youtube\/v3\/videos\?/.test(location)) {
    console.error(JSON.stringify({event:'yt_resumable_init_failed',status:init.status}));
    return json({error:'youtube_upload_session_failed',http_status:init.status},502);
  }
  const sent=await fetch(location,{method:'PUT',headers:{'Authorization':`Bearer ${token}`,
    'Content-Type':'video/mp4','Content-Length':String(media.byteLength)},body:media});
  if (!sent.ok) {
    console.error(JSON.stringify({event:'yt_media_upload_failed',status:sent.status}));
    return json({error:'youtube_media_upload_failed',http_status:sent.status},502);
  }
  const video=await sent.json().catch(()=>({}));
  if (!/^[A-Za-z0-9_-]{6,32}$/.test(video.id||'')) return json({error:'youtube_video_id_missing'},502);
  await env.DB.prepare('INSERT INTO youtube_private_uploads (media_sha256,job_id,youtube_id,content_mode) VALUES (?,?,?,?)')
    .bind(sha,jobId||null,video.id,mode).run();
  console.log(JSON.stringify({event:'youtube_private_upload_saved',mode,video_id:video.id}));
  return json({status:'uploaded_private',youtube_id:video.id,privacy:'private',
    watch_url:`https://www.youtube.com/watch?v=${video.id}`});
}
